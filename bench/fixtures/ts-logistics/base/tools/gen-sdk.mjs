#!/usr/bin/env node
// Generates packages/sdk/gen/*.gen.ts from packages/sdk/api.json.
import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const spec = JSON.parse(readFileSync(join(root, 'packages/sdk/api.json'), 'utf8'));
const HEADER = `// Code generated by tools/gen-sdk.mjs from packages/sdk/api.json. DO NOT EDIT.\n// API ${spec.title} ${spec.version}\n`;

// ---- models ----
let models = HEADER + '\n';
for (const [name, fields] of Object.entries(spec.models)) {
  models += `export interface ${name} {\n`;
  for (const [f, t] of Object.entries(fields)) {
    const opt = f.endsWith('?');
    models += `  /** ${name}.${opt ? f.slice(0, -1) : f}${opt ? ' (optional)' : ''} */\n`;
    models += `  ${f}: ${t};\n`;
  }
  models += '}\n\n';
  models += `export function is${name}(v: unknown): v is ${name} {\n  if (typeof v !== 'object' || v === null) return false;\n  const o = v as Record<string, unknown>;\n`;
  for (const [f, t] of Object.entries(fields)) {
    if (f.endsWith('?')) continue;
    const prim = t === 'string' || t === 'number' || t === 'boolean' ? t : t.endsWith('[]') ? 'array' : 'object';
    models += prim === 'array' ? `  if (!Array.isArray(o.${f})) return false;\n` : prim === 'object' ? `  if (o.${f} === undefined) return false;\n` : `  if (typeof o.${f} !== '${prim}') return false;\n`;
  }
  models += '  return true;\n}\n\n';
}
writeFileSync(join(root, 'packages/sdk/gen/models.gen.ts'), models);

// ---- transport ----
const transport = `${HEADER}
export interface TransportOptions {
  baseUrl: string;
  apiKey: string;
  fetch?: (input: string, init: RequestInit) => Promise<Response>;
  userAgent?: string;
  timeoutMs?: number;
  retries?: number;
}

export interface RequestInit {
  method: string;
  headers: Record<string, string>;
  body?: string;
  signal?: AbortSignal;
}

export interface Response {
  status: number;
  ok: boolean;
  json(): Promise<unknown>;
  text(): Promise<string>;
}

export class ApiRequestError extends Error {
  readonly status: number;
  readonly body: unknown;
  constructor(status: number, body: unknown) {
    super(\`request failed with status \${status}\`);
    this.status = status;
    this.body = body;
  }
}

export class Transport {
  private readonly o: TransportOptions;
  constructor(o: TransportOptions) {
    this.o = o;
  }

  async request<T>(method: string, path: string, opts: { query?: Record<string, string | undefined>; body?: unknown } = {}): Promise<T> {
    const qs = Object.entries(opts.query ?? {})
      .filter(([, v]) => v !== undefined)
      .map(([k, v]) => \`\${encodeURIComponent(k)}=\${encodeURIComponent(String(v))}\`)
      .join('&');
    const url = \`\${this.o.baseUrl.replace(/\\/$/, '')}${spec.basePath}\${path}\${qs ? '?' + qs : ''}\`;
    const f = this.o.fetch ?? (globalThis as unknown as { fetch: TransportOptions['fetch'] }).fetch;
    if (!f) throw new Error('no fetch implementation available');
    const attempts = (this.o.retries ?? 2) + 1;
    let last: unknown;
    for (let i = 0; i < attempts; i++) {
      const res = await f(url, {
        method,
        headers: {
          'x-api-key': this.o.apiKey,
          'content-type': 'application/json',
          'user-agent': this.o.userAgent ?? 'kestrel-sdk/${spec.version}',
        },
        body: opts.body === undefined ? undefined : JSON.stringify(opts.body),
      });
      if (res.status >= 500 && i < attempts - 1) {
        last = res;
        continue;
      }
      const text = await res.text();
      const parsed = text ? JSON.parse(text) : undefined;
      if (!res.ok) throw new ApiRequestError(res.status, parsed);
      return parsed as T;
    }
    throw last instanceof Error ? last : new Error('request failed');
  }
}
`;
writeFileSync(join(root, 'packages/sdk/gen/transport.gen.ts'), transport);

// ---- clients ----
for (const [group, ops] of Object.entries(spec.clients)) {
  const cls = group[0].toUpperCase() + group.slice(1) + 'Client';
  const types = new Set();
  for (const op of ops) {
    if (op.body) types.add(op.body);
    types.add(op.returns);
  }
  let src = `${HEADER}\nimport type { ${[...types].sort().join(', ')} } from './models.gen.ts';\nimport type { Transport } from './transport.gen.ts';\n\n`;
  src += `export class ${cls} {\n  private readonly t: Transport;\n\n  constructor(t: Transport) {\n    this.t = t;\n  }\n`;
  for (const op of ops) {
    const params = [...op.path.matchAll(/\{(\w+)\}/g)].map((m) => m[1]);
    const args = [...params.map((p) => `${p}: string`)];
    if (op.body) args.push(`body: ${op.body}`);
    if (op.query) args.push(`query: { ${op.query.map((q) => `${q}?: string`).join('; ')} } = {}`);
    const path = op.path.replace(/\{(\w+)\}/g, (_m, p) => `\${encodeURIComponent(${p})}`);
    src += `\n  /**\n   * ${op.doc}\n   *\n   * ${op.method} ${spec.basePath}${op.path}\n   */\n`;
    src += `  async ${op.name}(${args.join(', ')}): Promise<${op.returns}> {\n`;
    src += `    return this.t.request<${op.returns}>('${op.method}', \`${path}\`, {${op.query ? ' query,' : ''}${op.body ? ' body' : ''} });\n  }\n`;
  }
  src += '}\n';
  writeFileSync(join(root, `packages/sdk/gen/${group}Client.gen.ts`), src);
}
console.log('sdk generated');
