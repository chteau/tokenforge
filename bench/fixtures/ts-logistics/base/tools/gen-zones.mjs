const range = (a, b) => Array.from({ length: b - a + 1 }, (_, i) => a + i);
const REMOTE = {
  HS: range(1, 9),
  KW: range(1, 17),
  IV: [...range(41, 49), 51, 55, 56],
  PA: [20, ...range(41, 49), ...range(60, 78)],
  PH: [...range(30, 44), 49, 50],
  KA: [27, 28],
};
const EXTENDED = { ZE: range(1, 3), TR: range(21, 25) };
const OUTER = {
  AB: [...range(31, 38), ...range(41, 56)],
  BT: range(1, 94),
  DD: range(8, 11),
  DG: range(1, 16),
  FK: range(17, 21),
  IV: [...range(1, 40), ...range(52, 54), ...range(57, 63)],
  PA: [...range(21, 40)],
  PH: [...range(1, 29), ...range(45, 48)],
  PO: range(30, 41),
  TD: range(1, 15),
  LD: range(1, 8),
  SY: range(14, 25),
  LL: range(30, 78),
  TR: [...range(1, 20), 26, 27],
  EX: range(31, 39),
  CA: range(17, 28),
  YO: range(60, 62),
};

function zoneFor(area, n) {
  if (EXTENDED[area]?.includes(n)) return 'X';
  if (REMOTE[area]?.includes(n)) return 'R';
  if (OUTER[area]?.includes(n)) return 'B';
  return 'A';
}

const gbLines = [];
for (const [area, max] of Object.entries(GB_AREAS)) {
  for (let n = 1; n <= max; n++) gbLines.push(`  ${JSON.stringify(area + n)}: '${zoneFor(area, n)}',`);
  gbLines.push(`  ${JSON.stringify(area + '*')}: '${zoneFor(area, -1)}',`);
}
for (const area of ['IM', 'JE', 'GG']) gbLines.push(`  ${JSON.stringify(area + '*')}: 'X',`);

const FR_OUTER = ['04', '05', '09', '15', '23', '43', '46', '48', '65', '66', '73', '74'];
const frLines = [];
for (let d = 1; d <= 95; d++) {
  const k = String(d).padStart(2, '0');
  const z = k === '20' ? 'R' : FR_OUTER.includes(k) ? 'B' : 'A';
  frLines.push(`  '${k}': '${z}',`);
}
for (const k of ['971', '972', '973', '974', '975', '976', '977', '978', '984', '986', '987', '988']) frLines.push(`  '${k}': 'X',`);

